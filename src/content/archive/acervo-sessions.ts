import type { ArchiveSession } from "./types";
import { buildStandardSession } from "./standard-session";

function withResultado(session: ArchiveSession, file: string | null, title = "Resultado"): ArchiveSession {
  if (!file) return session;
  return {
    ...session,
    materials: [
      ...session.materials,
      {
        id: "resultado",
        materialId: "resultado",
        kind: "pdf",
        icon: "R",
        title,
        description: "Divulgação oficial do resultado desta edição.",
        category: "Resultado",
        action: "Abrir PDF",
        href: "#material-resultado",
        dimmed: false,
      },
    ],
  };
}

