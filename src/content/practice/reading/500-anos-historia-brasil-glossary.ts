export function normalizeGlossKey(word: string): string {
  return word
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^\p{L}\p{N}-]+/gu, "")
    .trim();
}

export function lookupSeedGloss(word: string): WordGloss | undefined {
  const key = normalizeGlossKey(word);
  if (!key) return undefined;
  return historiaBrasil500AnosGlossary[key];
}

/** Alias used by the video lesson UI. */
export function lookupLocalGloss(word: string): WordGloss | undefined {
  return lookupSeedGloss(word);
}

